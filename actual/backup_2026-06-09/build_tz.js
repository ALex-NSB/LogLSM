function H1(text) { return new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun(text)] }); }
function H2(text) { return new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun(text)] }); }
function H3(text) { return new Paragraph({ heading: HeadingLevel.HEADING_3, children: [new TextRun(text)] }); }
function P(text, opts = {}) { return new Paragraph({ children: [new TextRun({ text, ...opts })], spacing: { after: 120 } }); }
function PB(label, text) { return new Paragraph({ children: [new TextRun({ text: label, bold: true }), new TextRun({ text })], spacing: { after: 120 } }); }
function Bullet(text, level = 0) {
  return new Paragraph({ numbering: { reference: "bullets", level }, children: [new TextRun(text)], spacing: { after: 60 } });
}
function Num(text, level = 0) {
  return new Paragraph({ numbering: { reference: "numbers", level }, children: [new TextRun(text)], spacing: { after: 60 } });
}
function Note(text) {
  return new Paragraph({
    children: [new TextRun({ text: "Открытый вопрос / требует решения: ", bold: true, color: "B00000" }),
               new TextRun({ text, color: "B00000", italics: true })],
    spacing: { after: 160 }, indent: { left: 360 },
    border: { left: { style: BorderStyle.SINGLE, size: 18, color: "B00000", space: 8 } }
  });
}
function cell(text, opts = {}) {
  return new TableCell({
    borders,
    width: { size: opts.width || FULL_W / 2, type: WidthType.DXA },
    shading: opts.head ? { fill: headFill, type: ShadingType.CLEAR } : undefined,
    verticalAlign: VerticalAlign.CENTER,
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    children: [new Paragraph({ children: [new TextRun({ text, bold: !!opts.head })] })]
  });
}
function table(widths, rows) {
  return new Table({
    width: { size: widths.reduce((a,b)=>a+b,0), type: WidthType.DXA },
    columnWidths: widths,
    rows: rows.map((r, ri) => new TableRow({
      children: r.map((c, ci) => cell(c, { width: widths[ci], head: ri === 0 }))
    }))
  });
}
