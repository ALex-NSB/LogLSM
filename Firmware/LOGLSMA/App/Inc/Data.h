#define GYRO_THRESHOLD          600

/* Состояния RegistratorData.state — общий автомат SLEEP->CONFIRM->ROTATING
 * (RotationStateStep(), com.c). 02.07.2026, финальная версия: сон один и
 * тот же ВСЕГДА (настоящий Stop2), независимо от того, подключён кабель
 * или нет — не вопрос экономии энергии, а вопрос проверки: условия
 * выхода из сна (WKUP1/WKUP2) должны отрабатывать одинаково что на
 * стенде, что в поле. RotationStateStep() вызывается ТОЛЬКО из main.c;
 * Service()/BENCH (com.c) распознаванием вращения не занимается вообще
 * (только LTP-команды) — единственная разница между «автономно» и
 * «сервисно» — внутри активной фазы, в момент завершения цикла:
 * PushCycleRecord() сама проверяет текущий уровень WKUP1 и либо
 * дублирует данные цикла по LTP, либо нет; в обоих случаях далее —
 * назад в SLEEP, без исключений.
 *
 * SLEEP — гироскоп выключен, включён только акселерометр (Wake-Up
 * Detection) — реальный Stop2 (~2 мкА), будит аппаратно WKUP2/PC13.
 * Такое пробуждение может быть ложным (удар, тряска — не вращение
 * колеса), поэтому гироскоп не включается сразу на постоянно.
 * CONFIRM — включаем гироскоп на короткое ОКНО (CONFIRM_WINDOW_POLLS
 * опросов): если за это окно RotationDetected() (обычный гироскопный
 * порог GYRO_THRESHOLD) подтвердит реальное вращение — переходим в
 * ROTATING; если нет — гироскоп выключается назад, возврат в SLEEP.
 * ROTATING — вращение подтверждено, идёт цикл, дебаунс
 * ROTATION_DEBOUNCE_N перед завершением. */
#define REG_STATE_SLEEP     0u   /* в т.ч. Stop2 — акселерометр сам будит */
#define REG_STATE_ROTATING  1u   /* вращение подтверждено, идёт цикл */
#define REG_STATE_CONFIRM   2u   /* проснулись по акселерометру, гироскоп
                                   * включён, проверяем окно */

/* Длина окна проверки CONFIRM в опросах Poll_Sensor() (каждый ~240 мс при
 * ODR=12.5 Гц, см. Data.c). НЕ откалибровано — подобрать на стенде так,
 * чтобы окно было заметно длиннее одного цикла шума, но не расходовало
 * заряд на ложные срабатывания дольше необходимого. */
#define CONFIRM_WINDOW_POLLS   5u

/* Дебаунс «нет детекта» перед завершением цикла ROTATING.
 * 06.07.2026: поднят 3→6 (~720 мс → ~1.44 с) — МЕТОД 1 против дробления
 * циклов: на разгоне стенда с нуля и при смене скорости показания гироскопа
 * кратковременно проседают ниже порога, и при N=3 один физический поворот
 * рвался на обрывки. Больший N держит цикл цельным через короткие просадки.
 * ⚠ Значение тюнингуемое: слишком большое — медленно ловит реальный стоп
 * (цикл кажется длиннее на N опросов); подобрать на стенде. */
#define ROTATION_DEBOUNCE_N    6u

/* 3-уровневый автомат (11.07.2026): сколько подряд RTC-проверок без вращения
 * («Проверка») до ухода в глубокий сон (accel-wake, без таймера). При периоде
 * RTC ~2 c: 3 → ~6 c тишины после активности, потом deep sleep. Тюнингуемое. */
#define IDLE_CHECKS_TO_DEEP    3u

/* Сервисное окно на кабеле (12.07.2026): при подключённом кабеле (WKUP1=1)
 * уходим в глубокий сон НЕ через 3 проверки, а через это большее число ~ 15
 * (при RTC ~2 c ≈ 30 c). Цель: на кабеле после пробуждения устройство долго
 * остаётся в «Проверке» (достижимо по LTP ~80%: Flash-scan досчитывает, 0x22
 * доходит) — раньше спящее в глубоком сне устройство не отвечало (бар Флеш
 * висел, стоп не проходил). В ПОЛЕ (кабеля нет) — быстрый глубокий сон
 * (IDLE_CHECKS_TO_DEEP), автономность. Глубокий сон ВХОДИТ и с кабелем — просто
 * после ~30 c тишины (на стенде проверяется паузой длиннее окна). */
#define IDLE_CHECKS_TO_DEEP_CABLE  15u

/* Калибровочный коэффициент скорости — НЕЙТРАЛЬ 1.0 (12.07.2026).
 * История: 11.07 вечером гироскоп занижал −5.4%@74, поставили k=1.057 (74→+0%).
 * 12.07 УТРОМ тот же k дал +4…+5.4% (перекоррекция!) — сырая погрешность за
 * ночь ушла с −5.4% до ≈−1.6%, причина почти наверняка ТЕМПЕРАТУРА (gain
 * MEMS-гироскопа температурозависим). ВЫВОД: один жёсткий коэффициент под одну
 * температуру нестабилен → возвращаем НЕЙТРАЛЬ (честный сырой сдвиг на дисплее).
 * Настоящая калибровка — в мастере вкладки «Калибровка», с ТЕМПЕРАТУРНОЙ
 * компенсацией (есть TMP117 + температура IMU): хранить k(T) или мерить в
 * рабочих условиях. См. session_notes_2026-07-11_speed_avg_axis_fix.md §10. */
#define SPEED_CALIB_COEF       1.0f

/* МЕТОД 2 против дробления (06.07.2026): минимальная длительность цикла (сек).
 * Циклы короче НЕ пишутся во Flash и не пушатся — это фрагменты (durS=0/1) с
 * разгона, не реальные циклы. Страховка поверх дебаунса: даже если обрывок
 * проскочил, он не засоряет Flash/журнал/график. Совпадает с фильтром ≥2 с на
 * стороне LOGLSMW (там прячем с глаз, здесь чистим в корне). */
#define MIN_CYCLE_SEC          2u

/* ГИРОСКОП-ТРОТТЛ переходом Пассивный→Активный (12.07.2026). Гироскоп — самый
 * дорогой узел (combo HP ~550 мкА), поэтому не включаем его на КАЖДОЕ accel-
 * пробуждение. accel Wake-Up слушаем всегда (Пассивный, ~7 мкА), а вход в
 * Активный (гироскоп-проверка) разрешаем не чаще раза в gyroRecheckSec.
 * Интервал ЭСКАЛИРУЕТ (удвоение) при упорной вибрации без вращения и
 * СБРАСЫВАЕТСЯ в MIN при подтверждённом вращении / после цикла. Floor = 1 с
 * (разрешение всегда-идущего календаря RTC; при чистом старте из тишины
 * задержка всё равно ≈ прогрев гироскопа 0.4 с — elapsed велик, троттл не
 * мешает). CAP ограничивает частоту гироскоп-пульсов в вибро-шторме. */
#define GYRO_RECHECK_MIN_SEC   1u
#define GYRO_RECHECK_MAX_SEC   16u

/* Вибрация за цикл (12.07.2026). Признак = AC-компонента модуля accel: |a| =
 * √(ax²+ay²+az²) держит ~1g базу (гравитация) + вибрацию; медленный EMA
 * (VIB_DC_ALPHA) оценивает эту DC-базу (гравитация/наклон), а отклонение от неё
 * = вибрация (ориентационно-независимо, наклон не даёт ложного пика). Копим ПИК
 * и RMS за фазу вращения. ⚠ accel читается ~12.5 Гц (по DRDY гироскопа) —
 * это КОЭФФИЦИЕНТ-проба «сколько трясёт», а не спектр (для спектра — Logger +
 * DSP на ПК). Alpha 0.05 ≈ tau 20 выборок (~1.6 c): орт. изменения медленнее
 * проходят как DC, вибрация быстрее — как AC. */
#define VIB_DC_ALPHA           0.05f
/* Шаг median-трекера «уровня» (19.07.2026): ±β·vibLvl за сэмпл. 0.03 = сходится
 * за ~100 сэмплов, редкие удары почти не двигают (медиана робастна к выбросам). */
#define VIB_LVL_BETA           0.03f
/* Детектор полок скорости (19.07.2026). Полоса «та же полка» = ±max(FRAC·avg,
 * MIN) об/мин; выход за полосу PLATEAU_DEBOUNCE выборок подряд = граница полки. */
#define PLATEAU_MAX_N          8u
#define PLATEAU_BAND_FRAC      0.15f
#define PLATEAU_BAND_MIN       4.0f
#define PLATEAU_DEBOUNCE       3u

