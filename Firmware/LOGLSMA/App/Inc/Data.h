#pragma pack(pop)

#pragma pack(push,1)
typedef struct
{
  RTC_DateTime startTimeStamp;
  RTC_DateTime stopTimeStamp;
  RTC_DateTime lastRotStamp;   /* время ПОСЛЕДНЕГО детекта вращения — им ставим
                                * Стоп цикла (без хвоста дебаунса, 11.07.2026) */
  uint16_t maxRate;
  uint16_t maxVibr;
} RotationData;
#pragma pack(pop)

typedef struct
{
  uint8_t state;
  uint8_t noDetectCount;   /* дебаунс: сколько подряд «нет детекта» в state=1 */
  uint8_t confirmPolls;    /* счётчик опросов в REG_STATE_CONFIRM (02.07.2026) */
  uint8_t monitoringActive; /* 02.07.2026: автомат SLEEP->CONFIRM->ROTATING
                             * (режим A) запускается ТОЛЬКО явной командой
                             * CMD_START_REGISTER (0x1D, cmdStartRegister() в
                             * com.c) — не автоматически по состоянию WKUP1.
                             * main.c проверяет этот флаг перед тем, как
                             * вообще трогать автомат; 0 по умолчанию при
                             * старте прошивки. */
  uint8_t testNoSleep;      /* Режим «Тест» (CMD_START_TEST 0x23): тот же
                             * автомат, что и «Работа», но в фазе SLEEP НЕ
                             * уходим в Stop2 — бодрствуем, обслуживаем UART
                             * (ComPoll) и ловим фронт INT1/WKUP2 опросом
                             * флага WUF2 на ходу. 0 = «Работа» (со сном),
                             * 1 = «Тест». Снимается в cmdStopRegister(). */
  uint32_t totalSec;
  RotationData rot;
  LSM6DSO_Object_t *lsm;
  int32_t sensorData[256];
  int32_t avgGyro;
  uint32_t len;
  int32_t  rateSum;    /* сумма мгновенных rate за фазу ROTATING (для среднего) */
  uint32_t rateCount;  /* число выборок в rateSum */
  uint16_t avgRate;    /* среднее об/мин за цикл — отчётная «Скорость».
                        * rot.maxRate остаётся ПИКОВЫМ (короткие выбросы). */
  uint8_t  rotWarmup;  /* 1 = первую (разгонную) выборку цикла в среднее не берём */
  /* ДЕТЕКТОР ПОЛОК скорости (19.07.2026, только сервис/тест — в Flash уходит
   * лишь rot.maxRate за цикл; полки шлём живьём при кабеле). Непрерывное
   * вращение сегментируем по стабильным «полкам», на каждой берём МАКСИМУМ. */
  int32_t  plateauMax;   /* максимум rate на текущей полке */
  float    plateauAvg;   /* EMA rate текущей полки (опорное для полосы) */
  uint8_t  plateauInit;  /* 0 = полка ещё не засеяна */
  uint8_t  plateauChg;   /* счётчик подряд-выборок ВНЕ полосы (дебаунс границы) */
  uint16_t subMax[PLATEAU_MAX_N];  /* максимумы завершённых полок цикла */
  uint8_t  subCount;     /* число завершённых полок (для суб-пуша) */
  float    vibDc;      /* EMA-оценка DC (гравитация/наклон) модуля accel, LSB */
  uint8_t  vibDcInit;  /* 0 = vibDc ещё не засеян первой выборкой */
  float    vibPeak;    /* КАНАЛ 1 «пики»: пик |amag − DC| за цикл, МГ (ловит удар) */
  float    vibLvl;     /* канал 1 «уровень»: робастная медиана |dev|, МГ (удароустойчива) */
  uint8_t  vibLvlInit; /* 0 = vibLvl ещё не засеян */
  uint32_t vibCount;   /* общий счётчик выборок вибрации за цикл (оба канала) */
  float    vibSumSq;   /* канал 2 (jerk) RMS вспом.; для канала 1 больше не нужен */
  /* КАНАЛ 2 вибрации на варианте A (12.07.2026): импульсность/ударность =
   * |Δ|a|| между соседними отсчётами (резкие толчки). На варианте B этот слот
   * займёт физический high-g accel. */
  float    jerkPeak;   /* канал 2: пик |Δamag| за цикл, МГ */
  float    jerkSumSq;  /* канал 2: Σ jerk² за цикл (RMS), мг² */
  float    prevAmag;   /* предыдущий |a| для разности (jerk), мг */
  uint8_t  prevAmagInit; /* 0 = prevAmag ещё не засеян */
  /* АВТОРЕЙНДЖ шкалы accel на время вращения (18.07.2026): сидим на ±2g
   * (макс. чувствительность), при клипе сэмпла удваиваем шкалу до ±16g.
   * Вибрация копится СРАЗУ В МГ (accSensMg — текущая чувствительность),
   * поэтому смена шкалы не ломает аккумуляторы. Возврат ±2g — при уходе
   * в сон (Wake-Up порог завязан на шкалу). */
  uint8_t  accFs;      /* текущая полная шкала accel: 2/4/8/16 g */
  float    accSensMg;  /* чувствительность текущей шкалы, мг/LSB */
  uint8_t  deepSleep;  /* 3-уровневый автомат (11.07.2026): 1 = глубокий сон
                        * (accel-wake/EXTI13, БЕЗ RTC), 0 = «проверка» (RTC-опрос). */
  uint8_t  idleChecks; /* подряд RTC-проверок без вращения; >= IDLE_CHECKS_TO_DEEP
                        * → уходим в глубокий сон (deepSleep=1). */
  /* Гироскоп-троттл Пассивный→Активный (12.07.2026, см. GYRO_RECHECK_*_SEC). */
  uint16_t gyroRecheckSec;    /* текущий интервал гироскоп-перепроверки (эскалация) */
  uint8_t  gyroCheckPending;  /* 1 = следующее пробуждение проверить гироскопом БЕЗ
                               * троттла (взводится на старте и после цикла — чтобы
                               * первый детект из тишины был мгновенным) */
  RTC_DateTime lastGyroCheck; /* метка последней гироскоп-проверки — от неё считаем
                               * elapsed для троттла (календарь RTC, 1 с) */
} RegistratorData;

