#ifndef BOOT_H
#define BOOT_H
/* ---------------------------------------------------------------------------
 * boot.h — загрузчик LogLSM: карта, договор, коды LTP (05.08.2026).
 *
 * ИДЕОЛОГИЯ (зафиксировано 05.08.2026).
 *   Загрузчик — НЕ отдельная прошивка. Это часть ОДНОГО образа LOGLSMA,
 *   просто уложенная линкером в отдельную область флеша наверху (стр.113..120)
 *   и никогда не перезаписываемая при обновлении по кабелю.
 *   Прошивок по-прежнему одна, собирается одним проектом, шьётся одним ELF.
 *
 *   Вектором сброса загрузчик не владеет: внизу, на 0x08000000, как и раньше,
 *   лежит приложение. Прибор стартует обычным образом. Управление загрузчик
 *   получает ВЫЗОВОМ по команде LTP 0x39; обратно — через сброс (команда GO),
 *   чтобы новое приложение стартовало с чистого железа.
 *
 * ⚠ ТРИ ПРАВИЛА ЖИЗНИ В .bootsec — нарушение любого = падение посреди заливки
 *   с последующим лечением по SWD:
 *
 *   1. Код загрузчика не смеет вызывать НИЧЕГО из области приложения — она в
 *      этот момент стёрта. Это касается и невидимых вызовов, которые
 *      подставляет компилятор: memcpy при копировании структур, помощники для
 *      деления и 64-битной арифметики. Отсюда ручные циклы вместо memcpy и
 *      деление только на константы-степени двойки.
 *   2. У загрузчика не должно быть инициализированных статиков (.data): их
 *      содержимое подкладывает стартовый код приложения из НОВОГО образа, а
 *      сам загрузчик остался от старой прошивки по SWD. Всё состояние
 *      обнуляется явно, в начале boot_loader_run().
 *   3. Приложение зовёт загрузчик НЕ по имени функции, а по указателю,
 *      лежащему в первом слове секции (BOOT_ENTRY_PTR_ADDR). Имя
 *      разрешается линкером в адрес ТЕКУЩЕЙ сборки, а во флеше лежит
 *      секция от предыдущей — адреса разъедутся молча.
 *
 * ⚠ ДВА СЛЕДСТВИЯ ПЕРЕХОДА БЕЗ СБРОСА:
 *   • IWDG, запущенный приложением (~32 с), продолжает тикать — программно он
 *     не выключается. Загрузчик гладит его сам.
 *   • Стр.0 — таблица векторов приложения. Пока идёт заливка, приложения
 *     фактически нет, и снятие питания оставило бы прибор без работающего
 *     вектора сброса (лечение только SWD). Поэтому на время заливки в стр.0
 *     лежит АВАРИЙНЫЙ вектор, указывающий на сам загрузчик: обрыв означает
 *     всего лишь «прибор включился в загрузчик и ждёт повторной заливки».
 *     Настоящие вектора приезжают последними (LOGLSMW шлёт начало образа в
 *     конце) — уязвимы только эти десятки миллисекунд.
 *     ⚠ Отсюда же требование к правилу 2: при аварийном старте до загрузчика
 *     не выполняется вообще никакого стартового кода.
 * ------------------------------------------------------------------------- */
#include <stdint.h>

/* --- Карта внутренней Flash (128 стр. × 2 КБ) ------------------------------ */
#define BOOT_PAGE_SIZE     2048u
#define BOOT_FLASH_BASE    0x08000000u

#define APP_PAGE_FIRST     0u          /* приложение: стр.0..112, база 0x08000000 */
#define APP_PAGE_LAST      112u
#define APP_BASE           0x08000000u
#define APP_MAX_SIZE       ((APP_PAGE_LAST - APP_PAGE_FIRST + 1u) * BOOT_PAGE_SIZE)  /* 226 КБ */

#define BOOT_SEC_PAGE_FIRST 113u       /* .bootsec: стр.113..120 (16 КБ) */
#define BOOT_SEC_PAGE_LAST  120u
#define BOOT_SEC_BASE       0x08038800u /* = 113 × 2048 */
#define BOOT_SEC_SIZE       ((BOOT_SEC_PAGE_LAST - BOOT_SEC_PAGE_FIRST + 1u) * BOOT_PAGE_SIZE)

/* Первое слово секции = адрес boot_loader_run() (см. правило 3 выше).
 * Кладёт его линкер, см. секцию .bootsec в STM32L433XX_FLASH.ld. */
#define BOOT_ENTRY_PTR_ADDR BOOT_SEC_BASE

/* Служебные страницы (загрузчик их не трогает никогда):
 *   121 журнал активаций, 123 паспорт+калибровки, 124..127 журнал рестартов. */

/* --- Коды LTP (в приложении заняты до 0x38 включительно) ------------------- */
#define LTP_CMD_BOOT_ENTER 0x39u   /* приложение: отдать управление; загрузчик: «я тут» */
#define LTP_CMD_BOOT_BEGIN 0x3Au   /* [0..3]=размер [4..7]=CRC32 → стереть под образ */
#define LTP_CMD_BOOT_DATA  0x3Bu   /* [0..3]=смещение [4..]=данные (≤256 Б) */
#define LTP_CMD_BOOT_END   0x3Cu   /* сверить CRC32 записанного образа */
#define LTP_CMD_BOOT_GO    0x3Du   /* ответить и уйти в сброс → стартует новое приложение */

/* Ответы BEGIN/DATA/END/GO: 1 байт кода. */
#define BOOT_OK            0x00u
#define BOOT_ERR_SIZE      0x01u   /* размер 0 или больше области приложения */
#define BOOT_ERR_ERASE     0x02u   /* ошибка стирания */
#define BOOT_ERR_PROGRAM   0x03u   /* ошибка записи */
#define BOOT_ERR_SEQ       0x04u   /* DATA без BEGIN / смещение за пределами образа */
#define BOOT_ERR_CRC       0x05u   /* CRC32 принятого образа не сошёлся */
#define BOOT_ERR_SHORT     0x06u   /* END раньше, чем принят весь образ */

#define BOOT_CHUNK_MAX     256u    /* максимум данных в одном DATA */

/* Метка «отвечает загрузчик» в ответе на 0x02/0x39:
 * [0]=BOOT_WHOAMI_MARK, [1..5]=версия ГГ ММ ДД ЧЧ ММ, [6..]=имя с '\0'.
 * У приложения в байте [0] — WHO_AM_I датчика (0x6C/0x70), не пересекается. */
#define BOOT_WHOAMI_MARK   0xB0u
#define BOOT_DEV_NAME      "LogLSMboot"

/* Точка входа. Не возвращается: работа заканчивается сбросом по команде GO.
 * ⚠ Звать ТОЛЬКО через указатель по BOOT_ENTRY_PTR_ADDR (правило 3). */
void boot_loader_run(void);

#endif /* BOOT_H */
