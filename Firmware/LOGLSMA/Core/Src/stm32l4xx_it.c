/**
  * @brief EXTI line[15:10] interrupt — PC13 (INT1 датчика LSM6DSO / WKUP2).
  * 05.07.2026: единственная задача этого прерывания — поднять ядро из Stop2
  * («Работа»/режим A). Из Stop2 выход возможен ТОЛЬКО по EXTI, SYS_WKUP2
  * пробуждает лишь Standby. HAL_GPIO_EXTI_IRQHandler сбрасывает pending
  * EXTI13; опознание источника (WKUP2 vs WKUP1) делает main() по флагам
  * WUF2/WUF1 после выхода из Stop2. Отдельный callback не нужен —
  * дефолтный (weak) пустой, зацикливания нет. */
void EXTI15_10_IRQHandler(void)
{
  HAL_GPIO_EXTI_IRQHandler(GPIO_PIN_13);
}

/**
  * @brief RTC wake-up timer interrupt — периодический будильник Stop2 в «Работе»
  * (11.07.2026). RTC тактируется от LSE/LSI независимо от ядра, поэтому это
  * самый надёжный источник выхода из Stop2 (в отличие от EXTI13/INT1, который
  * на стенде не поднимал ядро). HAL_RTCEx_WakeUpTimerIRQHandler сбрасывает
  * флаг WUTF и pending EXTI20; отдельный callback не нужен — сам факт выхода
  * из Stop2 обрабатывает main() после WFI. */
extern RTC_HandleTypeDef hrtc;
void RTC_WKUP_IRQHandler(void)
{
  HAL_RTCEx_WakeUpTimerIRQHandler(&hrtc);
}

